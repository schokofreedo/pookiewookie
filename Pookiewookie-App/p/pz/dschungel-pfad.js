      let placed = 0; while (placed < nh) { const i = Math.floor(rng() * NC); if (hole[i]) continue; hole[i] = true; placed++; }
      const total = NC - nh;
      const path = findPath(hole, total, rng); if (!path) continue;
      const s = path[0], g = path[total - 1];
      if (adj(s, g)) continue;
      const corner = i => (i % C === 0 || i % C === C - 1) && ((i / C | 0) === 0 || (i / C | 0) === C - 1);
      if (corner(s) && corner(g)) continue;
      if (snakeSolves(hole, total, s, g)) continue;
